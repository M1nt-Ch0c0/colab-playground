import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = fileURLToPath(new URL('../../', import.meta.url))
const target = new URL('../src/api/schema.d.ts', import.meta.url)
const spec = JSON.parse(execFileSync(process.env.PYTHON || 'python3', ['-c',
  'from draw_studio.application import create_app; import json; print(json.dumps(create_app().openapi()))',
], { cwd: root, encoding: 'utf8' }))

// The frontend uses the named wire models. HTTP routing stays in api/client.ts.
const types = await openapiTS({ ...spec, paths: {} }, { defaultNonNullable: false })
const output = '// Generated by npm run api:types from the FastAPI OpenAPI document.\n' + astToString(types)
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('API types changed. Run npm run api:types.')
} else {
  writeFileSync(target, output)
}
